#!/usr/bin/env node
/**
 * Generate shared/legalContent.ts from the four legal page components.
 *
 * Why generated rather than written. The legal pages were invisible to any
 * agent that does not run JavaScript, and phase 9 of the agent-surface plan
 * needs a real privacy policy url for the ChatGPT and Muse submissions. Every
 * other blank route in this work got condensed prose taken from the live page.
 * These four must not: a summarised privacy policy that an agent quotes, or
 * that a directory reviewer reads AS the policy, is worse than no policy at
 * all. So the crawler serves the actual text, extracted verbatim.
 *
 * Why a generated file rather than reading the TSX at runtime. The server does
 * not ship client source, so it cannot read these at request time. Generating
 * at build time puts the text somewhere the server can reach while keeping the
 * components the single place anyone edits.
 *
 * Safe to extract because the text is static: all four files were checked for
 * JSX interpolation in text positions and have none, and the tag vocabulary is
 * h2/h3/p/ul/li/strong/a/section. server/legal-content.test.ts re-runs this
 * extraction and fails if the committed output has drifted, so a legal edit
 * that does not regenerate is caught rather than silently served stale.
 *
 * Run: node scripts/extract-legal-content.mjs
 *      node scripts/extract-legal-content.mjs --check   (exit 1 on drift)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, resolve } from "node:path";

const repo = resolve(dirname(fileURLToPath(import.meta.url)), "..");

export const LEGAL_PAGES = [
  { slug: "privacy-policy", file: "PrivacyPolicy.tsx" },
  { slug: "terms-of-use", file: "TermsOfUse.tsx" },
  { slug: "risk-disclosure", file: "RiskDisclosure.tsx" },
  { slug: "disclaimers", file: "Disclaimers.tsx" },
];

const KEEP = new Set(["h2", "h3", "p", "ul", "ol", "li", "strong", "em", "a"]);

/** Pull a string prop off the LegalPageLayout opening tag. */
function prop(src, name) {
  const m = src.match(new RegExp(`${name}=\\{?["\`]([^"\`]*)["\`]\\}?`));
  return m ? m[1] : null;
}

/**
 * JSX to HTML, keeping only the tags that carry meaning.
 *
 * Attributes are dropped except href, because className and style are
 * presentation and a legal document's meaning does not live in them.
 */
export function jsxToHtml(src) {
  // The body is everything between the layout's opening tag and its close.
  //
  // Finding the end of that opening tag needs brace tracking, not the first
  // `>`. These components pass JSX in props (`icon={<Shield ... />}`), so a
  // naive indexOf(">") stops inside the prop and leaks `title="..."
  // lastUpdated="..." seo={...} >` into the document text. Caught by reading
  // the generated output rather than by the extractor complaining.
  const start = src.indexOf("<LegalPageLayout");
  if (start < 0) return null;
  let depth = 0;
  let open = -1;
  for (let i = start; i < src.length; i++) {
    const ch = src[i];
    if (ch === "{") depth++;
    else if (ch === "}") depth--;
    else if (ch === ">" && depth === 0) {
      open = i;
      break;
    }
  }
  const close = src.lastIndexOf("</LegalPageLayout>");
  if (open < 0 || close < 0) return null;
  let body = src.slice(open + 1, close);

  // JSX whitespace helpers and comments carry no text.
  body = body.replace(/\{["'`]\s*["'`]\}/g, " ").replace(/\{\/\*[\s\S]*?\*\/\}/g, "");

  const out = [];
  const tagRe = /<\/?([A-Za-z][A-Za-z0-9]*)\b([^>]*)>/g;
  let last = 0;
  let m;
  while ((m = tagRe.exec(body))) {
    const text = body.slice(last, m.index);
    if (text.trim()) out.push(text.replace(/\s+/g, " "));
    last = tagRe.lastIndex;

    const [, rawName, attrs] = m;
    const name = rawName.toLowerCase();
    const closing = m[0].startsWith("</");
    if (!KEEP.has(name)) continue;
    if (closing) {
      out.push(`</${name}>`);
    } else if (name === "a") {
      const href = attrs.match(/href=\{?["`]([^"`]*)["`]\}?/);
      out.push(href ? `<a href="${href[1]}">` : "<a>");
    } else {
      out.push(`<${name}>`);
    }
  }
  const tail = body.slice(last);
  if (tail.trim()) out.push(tail.replace(/\s+/g, " "));

  return out
    .join("")
    .replace(/\s+/g, " ")
    .replace(/>\s+</g, "><")
    .trim();
}

export function extractAll() {
  return LEGAL_PAGES.map(({ slug, file }) => {
    const src = readFileSync(join(repo, "client/src/pages", file), "utf8");
    return {
      slug,
      title: prop(src, "title") ?? slug,
      lastUpdated: prop(src, "lastUpdated"),
      html: jsxToHtml(src),
    };
  });
}

export function render(pages) {
  return `// GENERATED by scripts/extract-legal-content.mjs. Do not edit by hand.
//
// The legal pages' own text, extracted verbatim from the components in
// client/src/pages so a non-executing agent reads the real policy rather than
// a summary of it. Edit the components; run the script; commit both.
// server/legal-content.test.ts fails if this file has drifted from them.

export interface LegalPage {
  slug: string;
  title: string;
  lastUpdated: string | null;
  html: string;
}

export const LEGAL_CONTENT: LegalPage[] = ${JSON.stringify(pages, null, 2)};

export function getLegalPage(slug: string): LegalPage | undefined {
  return LEGAL_CONTENT.find((p) => p.slug === slug);
}
`;
}

if (process.argv[1]?.endsWith("extract-legal-content.mjs")) {
  const target = join(repo, "shared/legalContent.ts");
  const next = render(extractAll());
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(target, "utf8");
    } catch { /* missing counts as drift */ }
    if (current !== next) {
      console.error("shared/legalContent.ts is stale. Run: node scripts/extract-legal-content.mjs");
      process.exit(1);
    }
    console.log("legal content in sync");
  } else {
    writeFileSync(target, next);
    const pages = extractAll();
    for (const p of pages) console.log(`${p.slug.padEnd(16)} ${p.html.length} chars  (${p.lastUpdated ?? "no date"})`);
    console.log(`\nwrote ${target}`);
  }
}
