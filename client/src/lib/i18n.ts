export type Language = 'en' | 'es' | 'pt' | 'fr' | 'id' | 'de' | 'zh' | 'ar' | 'hi' | 'ja' | 'ru';

export interface LanguageInfo {
  code: Language;
  name: string;
  nativeName: string;
  flag: string;
  dir: 'ltr' | 'rtl';
}

